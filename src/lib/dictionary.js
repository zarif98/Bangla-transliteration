/**
 * Look up a word in the dictionary
 * @param {string} word - Bangla word to look up
 * @returns {string|null} - English transliteration or null if not found
 */
export function lookupWord(word) {
  return DICTIONARY[word] || null;
}

/**
 * Transliterate text using dictionary lookup with fallback
 * @param {string} text - Bangla text
 * @param {function} fallback - Fallback transliteration function for unknown words
 * @returns {string} - Transliterated text
 */
export function transliterateWithDictionary(text, fallback) {
  if (!text) return '';

  const words = text.split(/(\s+)/);
  return words.map((segment) => {
    if (/^\s+$/.test(segment)) return segment;

    const dictResult = lookupWord(segment);
    if (dictResult) return dictResult;

    return fallback ? fallback(segment) : segment;
  }).join('');
}

export { DICTIONARY };
export default lookupWord;
